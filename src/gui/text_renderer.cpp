TextRenderer::TextRenderer(SDL_Renderer *sdl_renderer, int size)
    : renderer(sdl_renderer), font_size(size) {
  // The font is natively 8x16; render at an integer multiple of that so glyphs
  // stay crisp (nearest-neighbour, no blur). font_size is the target height.
  int scale = size / GLYPH_SRC_H;
  if (scale < 1) {
    scale = 1;
  }
  glyph_width = GLYPH_SRC_W * scale;
  glyph_height = GLYPH_SRC_H * scale;
}

auto TextRenderer::init() -> bool { return renderer != nullptr; }

auto TextRenderer::render_text(const std::string &text, SDL_Color color)
    -> SDL_Texture * {
  if ((renderer == nullptr) || text.empty()) {
    return nullptr;
  }

  // For simplicity, render each string as a single texture
  // Calculate total width
  int const total_width = static_cast<int>(text.length()) * glyph_width;
  int const total_height = glyph_height;

  SDL_Texture *texture =
      SDL_CreateTexture(renderer, SDL_PIXELFORMAT_RGBA32,
                        SDL_TEXTUREACCESS_TARGET, total_width, total_height);

  if (texture == nullptr) {
    return nullptr;
  }

  // Create surface
  SDL_Surface *surface = SDL_CreateRGBSurfaceWithFormat(
      0, total_width, total_height, 32, SDL_PIXELFORMAT_RGBA32);

  if (surface == nullptr) {
    SDL_DestroyTexture(texture);
    return nullptr;
  }

  SDL_LockSurface(surface);
  auto *pixels = static_cast<uint32_t *>(surface->pixels);

  // Fill with transparent
  for (int y = 0; y < total_height; ++y) {
    for (int x = 0; x < total_width; ++x) {
      pixels[(y * surface->pitch / 4) + x] = 0x00000000;
    }
  }

  // Pack the colour for the surface's actual format. SDL_PIXELFORMAT_RGBA32 is
  // an endian-dependent alias (ABGR8888 on little-endian x86), so a hand-rolled
  // (r<<24)|(g<<16)|(b<<8)|a is wrong — it maps input red onto alpha, leaving any
  // colour with r==0 fully transparent. SDL_MapRGBA gets it right on any endian.
  const uint32_t packed =
      SDL_MapRGBA(surface->format, color.r, color.g, color.b, color.a);

  // Render each character
  for (size_t i = 0; i < text.length(); ++i) {
    char const c = text[i];
    int char_index = static_cast<int>(c) - 32;

    // Only render printable ASCII
    if (char_index < 0 || char_index >= 95) {
      char_index = 0; // Space
    }

    const uint8_t *bitmap = BITMAP_FONT[char_index];

    for (int y = 0; y < glyph_height; ++y) {
      int const src_y = (y * GLYPH_SRC_H) / glyph_height;
      for (int x = 0; x < glyph_width; ++x) {
        int const src_x = (x * GLYPH_SRC_W) / glyph_width;
        uint8_t const bit = bitmap[src_y] & (1 << (7 - src_x));

        if (bit != 0U) {
          int const px = (static_cast<int>(i) * glyph_width) + x;
          int const py = y;
          if (px < total_width && py < total_height) {
            pixels[(py * surface->pitch / 4) + px] = packed;
          }
        }
      }
    }
  }

  SDL_UnlockSurface(surface);
  SDL_UpdateTexture(texture, nullptr, surface->pixels, surface->pitch);
  SDL_FreeSurface(surface);

  return texture;
}

void TextRenderer::get_text_size(const std::string &text, int *w,
                                 int *h) const {
  if (w != nullptr) {
    *w = static_cast<int>(text.length()) * glyph_width;
  }
  if (h != nullptr) {
    *h = glyph_height;
  }
}

